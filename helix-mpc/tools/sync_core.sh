#!/bin/sh
# Regenerates helix-mpc/src/core_*.cpp: one wrapper per helix-core source (the SDK's build.py compiles
# src/*.cpp only). Run after adding or removing a file in helix-core/src.
set -e
cd "$(dirname "$0")/.."
rm -f src/core_*.cpp
for f in ../helix-core/src/*.cpp; do
  b=$(basename "$f" .cpp)
  printf '// Generated by tools/sync_core.sh: compiles helix-core/src/%s.cpp into the MPC plugin.\n#include "../../helix-core/src/%s.cpp"\n' "$b" "$b" > "src/core_$b.cpp"
done
printf '// Generated by tools/sync_core.sh.\n#include "../app/HelixMpcApp.cpp"\n' > src/app_HelixMpcApp.cpp
echo "wrappers: $(ls src/core_*.cpp | wc -l) core sources"
